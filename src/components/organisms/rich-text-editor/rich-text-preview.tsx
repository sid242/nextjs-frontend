"use client";

import * as React from "react";
import DOMPurify from "isomorphic-dompurify";

import { cn } from "@/lib/utils";

import "./rich-text-editor.css";

export interface RichTextPreviewProps {
  /** The HTML content string to display (e.g. from backend API) */
  content?: string | null;
  /** Alias for `content` */
  value?: string | null;
  /** Additional CSS class names for the container */
  className?: string;
  /** Visual presentation style: 'default' (unframed), 'bordered' (input-style frame), 'card' (elevated panel) */
  variant?: "default" | "bordered" | "card";
  /** Fallback content when the HTML is empty or whitespace */
  fallback?: React.ReactNode;
  /** Whether to show a fallback message when content is empty */
  showEmptyFallback?: boolean;
}

/** Check if string is empty or contains only empty HTML tags like `<p></p>` */
function isHtmlEmpty(html?: string | null): boolean {
  if (!html) return true;
  const stripped = html.replace(/<[^>]*>/g, "").trim();
  return stripped.length === 0 && !html.includes("<img") && !html.includes("<table");
}

/**
 * Universal RichTextPreview (Viewer) component.
 * Safely sanitizes and renders rich HTML text generated by RichTextEditor or backend endpoints.
 * Applies identical typography, tables, headings, image alignments, and code styling.
 *
 * @example
 * ```tsx
 * <RichTextPreview content={post.contentHtml} variant="bordered" />
 * ```
 */
export function RichTextPreview({
  content,
  value,
  className,
  variant = "default",
  fallback,
  showEmptyFallback = false,
}: RichTextPreviewProps) {
  const rawHtml = content ?? value ?? "";
  const isEmpty = isHtmlEmpty(rawHtml);

  const sanitizedHtml = React.useMemo(() => {
    if (!rawHtml || isEmpty) return "";
    return DOMPurify.sanitize(rawHtml, {
      ALLOWED_TAGS: [
        "h1",
        "h2",
        "h3",
        "h4",
        "h5",
        "h6",
        "p",
        "strong",
        "b",
        "em",
        "i",
        "u",
        "s",
        "sub",
        "sup",
        "ul",
        "ol",
        "li",
        "blockquote",
        "pre",
        "code",
        "a",
        "img",
        "span",
        "div",
        "br",
        "hr",
        "table",
        "thead",
        "tbody",
        "tr",
        "th",
        "td",
      ],
      ALLOWED_ATTR: [
        "href",
        "target",
        "rel",
        "src",
        "alt",
        "title",
        "width",
        "height",
        "style",
        "class",
        "data-align",
        "data-colwidth",
      ],
    });
  }, [rawHtml, isEmpty]);

  if (isEmpty && (showEmptyFallback || fallback)) {
    return (
      <div className={cn("text-muted-foreground py-2 text-xs italic", className)}>
        {fallback ?? "No content to preview."}
      </div>
    );
  }

  return (
    <div
      className={cn(
        "tiptap-preview",
        variant === "bordered" && "is-bordered",
        variant === "card" && "is-card",
        className,
      )}
    >
      <div className="ProseMirror-static" dangerouslySetInnerHTML={{ __html: sanitizedHtml }} />
    </div>
  );
}
